-- Tags (admin → แท็ก): a dictionary of what products are about, with every spelling
-- the shop uses ("ซาเวีย", "เซเวียร์", "Xavier" → ซาเวียร์). Items keep their names;
-- their tags are read from the text with this dictionary (js/tags.js), so they
-- follow the dictionary as it grows. Safe to run more than once: existing terms stay.

create table if not exists public.tag_terms (
  id         uuid primary key default gen_random_uuid(),
  kind       text not null check (kind in ('series','char','type','brand','sale')),
  tag        text not null,
  aliases    text[] not null default '{}',
  minus      text[] not null default '{}',   -- words that contain the tag but aren't it
  updated_at timestamptz not null default now(),
  unique (kind, tag)
);
alter table public.tag_terms enable row level security;
drop policy if exists tag_terms_admin_all on public.tag_terms;
create policy tag_terms_admin_all on public.tag_terms
  for all to authenticated using (public.is_admin()) with check (public.is_admin());

